package dev.logast;

import com.fasterxml.jackson.databind.ObjectMapper;
import dev.logast.model.LogCall;
import dev.logast.model.MethodInfo;
import dev.logast.parse.Hashing;
import dev.logast.parse.Pos;
import dev.logast.rules.MessageTemplate;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * #281: every log call with an id that lasts across runs and what happened to it: there before logast or added by it,
 * its wording (original, changed by logast, generated by logast, changed by a person), and a short history. The
 * coverage report is keyed by file:line, so a line added above shifts every id there; this one is keyed by the method
 * and matched by text, then by order, so a line keeps its id and history while the code around it moves.
 *
 * <p>An apply that writes observes the code twice: before its changes (what a person changed since the last run) and
 * after them (what logast changed). A dry run keeps nothing. Stored as {@code .logast/inventory.jsonl}, one call a line.
 */
public final class LogInventory {
    public static final String PATH = LogastDir.DIR + "/inventory.jsonl";
    public static final String PERSON = "person";
    public static final String LOGAST = "logast";
    private static final ObjectMapper JSON = new ObjectMapper();
    private static final int HISTORY = 8;

    /**
     * One log call. {@code origin}: existing | added; {@code wording}: original | logast | generated | person;
     * {@code history}: "run N: who what", the latest last.
     */
    public record Entry(String id, String method, String file, int line, String level, String text, String origin,
                        String wording, int run, List<String> history) {
    }

    private final Map<String, List<Entry>> byMethod = new LinkedHashMap<>();
    private final int run;

    private LogInventory(List<Entry> entries) {
        int last = 0;
        for (Entry e : entries) {
            byMethod.computeIfAbsent(e.method(), k -> new ArrayList<>()).add(e);
            last = Math.max(last, e.run());
        }
        this.run = last + 1;
    }

    /** The inventory kept under {@code root}, empty when there is none (or it cannot be read). */
    public static LogInventory load(Path root) {
        Path file = root.resolve(PATH);
        List<Entry> entries = new ArrayList<>();
        if (Files.isRegularFile(file)) {
            try {
                for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
                    if (!line.isBlank()) {
                        entries.add(JSON.readValue(line, Entry.class));
                    }
                }
            } catch (IOException | RuntimeException e) {
                entries.clear();   // unreadable: start over rather than fail the apply
            }
        }
        return new LogInventory(entries);
    }

    /** This run's number: one more than the latest run an entry records. */
    public int run() {
        return run;
    }

    /** Matches the log calls of {@code a} to the entries and records what {@code actor} changed. */
    public void observe(Analysis a, String actor) {
        Map<String, List<Entry>> now = new LinkedHashMap<>();
        for (MethodInfo m : a.index.methods()) {
            if (m.facts().logs.isEmpty() || m.owner().fqn().startsWith(a.supportPackage + ".")) {
                continue;
            }
            List<Entry> previous = byMethod.getOrDefault(m.key(), List.of());
            List<LogCall> calls = m.facts().logs;
            Entry[] matched = new Entry[calls.size()];
            Set<Entry> used = new HashSet<>();
            String[] texts = new String[calls.size()];
            for (int i = 0; i < calls.size(); i++) {
                texts[i] = text(calls.get(i));
            }
            // the same text first (the call moved or another was added), then by order (the text changed)
            for (int i = 0; i < calls.size(); i++) {
                for (Entry e : previous) {
                    if (!used.contains(e) && e.text().equals(texts[i])) {
                        matched[i] = e;
                        used.add(e);
                        break;
                    }
                }
            }
            // a reworded text keeps most of its words (an id moved to MDC, a phrase changed): the closest pairs first
            while (true) {
                int bi = -1;
                Entry best = null;
                double bestScore = 0.5;
                for (int i = 0; i < calls.size(); i++) {
                    if (matched[i] != null) {
                        continue;
                    }
                    for (Entry e : previous) {
                        double score = used.contains(e) ? 0 : overlap(e.text(), texts[i]);
                        if (score > bestScore || score == bestScore && best == null) {
                            bi = i;
                            best = e;
                            bestScore = score;
                        }
                    }
                }
                if (best == null) {
                    break;
                }
                matched[bi] = best;
                used.add(best);
            }
            List<Entry> rest = previous.stream().filter(e -> !used.contains(e)).toList();
            int next = 0;
            for (int i = 0; i < calls.size() && next < rest.size(); i++) {
                if (matched[i] == null) {
                    matched[i] = rest.get(next++);
                }
            }
            List<Entry> out = new ArrayList<>();
            for (int i = 0; i < calls.size(); i++) {
                LogCall lc = calls.get(i);
                int line = Pos.line(lc.call());
                String level = lc.level().name();
                String lineText = m.file().lineText(line);
                boolean generated = lineText != null && lineText.contains("logast:wording");
                Entry e = matched[i];
                if (e == null) {
                    boolean added = actor.equals(LOGAST);
                    String id = "LOG-" + Hashing.sha256(m.key() + "|" + texts[i] + "|" + i).substring(0, 8);
                    List<String> history = new ArrayList<>();
                    history.add("run " + run + ": " + (added ? "logast added it" : "found"));
                    out.add(new Entry(unique(id, out), m.key(), m.file().relPath(), line, level, texts[i],
                            added ? "added" : "existing", added ? (generated ? "generated" : LOGAST) : "original", run, history));
                    continue;
                }
                List<String> history = new ArrayList<>(e.history());
                String wording = e.wording();
                int last = e.run();
                if (!e.text().equals(texts[i])) {
                    wording = actor.equals(LOGAST) ? (generated ? "generated" : LOGAST) : PERSON;
                    history.add("run " + run + ": " + actor + " changed the text");
                    last = run;
                }
                if (!e.level().equals(level)) {
                    history.add("run " + run + ": " + actor + " changed the level " + e.level() + " -> " + level);
                    last = run;
                }
                while (history.size() > HISTORY) {
                    history.removeFirst();
                }
                out.add(new Entry(e.id(), m.key(), m.file().relPath(), line, level, texts[i], e.origin(), wording, last, history));
            }
            now.put(m.key(), out);
        }
        byMethod.clear();
        byMethod.putAll(now);
    }

    /** The entries, in file and line order. */
    public List<Entry> entries() {
        return byMethod.values().stream().flatMap(List::stream)
                .sorted(Comparator.comparing(Entry::file).thenComparingInt(Entry::line)).toList();
    }

    public void save(Path root) throws IOException {
        StringBuilder sb = new StringBuilder();
        for (Entry e : entries()) {
            sb.append(JSON.writeValueAsString(e)).append('\n');
        }
        Path file = root.resolve(PATH);
        Files.createDirectories(file.getParent());
        Files.writeString(file, sb.toString(), StandardCharsets.UTF_8);
    }

    public static final String WORDING_TODO = LogastDir.DIR + "/reports/wording-todo.txt";

    /**
     * #292: the log lines whose text is still logast's generated wording, by their lasting id, so the to-do list lives
     * outside the source: a line leaves it once someone rewords it (its wording becomes "person").
     */
    public String wordingTodo() {
        List<Entry> todo = entries().stream().filter(e -> "generated".equals(e.wording())).toList();
        StringBuilder sb = new StringBuilder("# log lines still in logast's generated words (#292): give each the words of the domain, "
                + "in the code or in .logast/decisions/messages.yaml; " + todo.size() + (todo.size() == 1 ? " line\n" : " lines\n"));
        todo.forEach(e -> sb.append(e.file()).append(':').append(e.line()).append("  ").append(e.id()).append("  ")
                .append(e.level()).append(" \"").append(e.text()).append("\"\n"));
        return sb.toString();
    }

    public void saveWordingTodo(Path root) throws IOException {
        Path file = root.resolve(WORDING_TODO);
        Files.createDirectories(file.getParent());
        Files.writeString(file, wordingTodo(), StandardCharsets.UTF_8);
    }

    /** The message text as written (a literal), else the code that builds it. */
    static String text(LogCall lc) {
        String t = lc.template() == null ? null : MessageTemplate.text(lc.template());
        return t != null ? t : lc.template() == null ? "" : lc.template().printTrimmed();
    }

    /** The share of the shorter text's words the other one has too (0 to 1). */
    static double overlap(String x, String y) {
        Set<String> a = words(x);
        Set<String> b = words(y);
        if (a.isEmpty() || b.isEmpty()) {
            return 0;
        }
        Set<String> small = a.size() <= b.size() ? a : b;
        Set<String> large = small == a ? b : a;
        return small.stream().filter(large::contains).count() / (double) small.size();
    }

    private static Set<String> words(String s) {
        Set<String> out = new HashSet<>();
        for (String w : s.toLowerCase(java.util.Locale.ROOT).split("[^a-z0-9]+")) {
            if (w.length() > 2) {
                out.add(w);
            }
        }
        return out;
    }

    private static String unique(String id, List<Entry> so) {
        String out = id;
        for (int n = 2; true; n++) {
            String candidate = out;
            if (so.stream().noneMatch(e -> e.id().equals(candidate))) {
                return out;
            }
            out = id + "-" + n;
        }
    }
}
